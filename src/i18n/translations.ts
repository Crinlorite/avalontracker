// Tipo del diccionario: keys son strings, values strings. No usamos
// tipo estricto de keys porque los componentes añaden keys conforme
// se traducen, sin forzar refactor masivo.
type Dict = Record<string, string>;

// Helper: completa un idioma con las keys de EN como fallback puro
// (devuelve el inglés tal cual). Útil para idiomas que aún no tienen
// traducciones y queremos que rendere algo utilizable.
function withFallback(partial: Dict, base: Dict): Dict {
  return { ...base, ...partial };
}

