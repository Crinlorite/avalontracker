// Reexporta los códigos para validación runtime y default-language detection.
export const SUPPORTED = Object.keys(translations);

// Helper para resolver una key en un idioma con fallback a EN y luego
// al literal de la key. Sustituye {var} por los valores de `vars`.
export function translate(lang: string, key: string, vars?: Record<string, string>): string {
  let s = translations[lang]?.[key] ?? translations.en?.[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, v);
    }
  }
  return s;
}

